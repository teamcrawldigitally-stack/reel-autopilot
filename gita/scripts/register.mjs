// Writes src/episodes.ts: every src/reels/epNN that has script.json + timing.json and a "scenes[].kind" (engine episodes).
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "src/reels");
const eps = fs.readdirSync(dir).filter((d) => {
  const s = path.join(dir, d, "script.json");
  if (!fs.existsSync(s) || !fs.existsSync(path.join(dir, d, "timing.json"))) return false;
  return JSON.parse(fs.readFileSync(s, "utf8")).scenes.every((x) => x.kind);
}).sort();
let out = `// generated by scripts/register.mjs\nimport type { Episode } from "./engine/types";\nimport type { Timing } from "./lib/timeline";\n`;
eps.forEach((e) => { out += `import ${e}s from "./reels/${e}/script.json";\nimport ${e}t from "./reels/${e}/timing.json";\n`; });
out += `\nexport const EPISODES: { id: string; ep: Episode; timing: Timing }[] = [\n`;
eps.forEach((e) => { out += `  { id: "${e}", ep: ${e}s as unknown as Episode, timing: ${e}t as unknown as Timing },\n`; });
out += `];\n`;
fs.writeFileSync(path.join(root, "src/episodes.ts"), out);
console.log("episodes:", eps.join(", "));
