def toks(s):
    return [re.sub(r"[\s।॥,?!.\-]", "", t) for t in s.split()]


problems = []
for key, r in R.items():
    imgs = set()
    for i, sc in enumerate(r["scenes"]):
        tk = toks(sc["voiceover"])
        for lab in sc["labels"]:
            if lab["word"] not in tk:
                problems.append(f"{key} s{i+1}: label word '{lab['word']}' not in voiceover")
        for h in sc["heroes"]:
            imgs.add(h["img"])
            if "prop" in h:
                imgs.add(h["prop"]["img"])
                if h["prop"]["word"] not in tk:
                    problems.append(f"{key} s{i+1}: prop word '{h['prop']['word']}' not in voiceover")
        if sc.get("questionWord") and sc["questionWord"] not in tk:
            problems.append(f"{key} s{i+1}: questionWord missing")
    assert r["scenes"][0]["voiceover"] == r["hook"], key
    imgs |= set(r["wallpaper"])
    out = {
        "topic": r["title"], "title": r["title"], "composition": "DevoReel", "look": "devo", "hook": r["hook"],
        "images": sorted(imgs), "floats": [], "caption": r["caption"], "hashtags": r["hashtags"],
        "music": r["music"], "scenes": r["scenes"], "palette": PAL, "wallpaper": r["wallpaper"], "typo": "gold",
    }
    json.dump(out, open(os.path.join(ROOT, "samples", f"dhan-{key}.json"), "w"), ensure_ascii=False, indent=2)
    words = sum(len(s["voiceover"].split()) for s in r["scenes"])
    print(f"dhan-{key}: {len(r['scenes'])} scenes, {words} words")
print("\n".join(problems) or "all cue words OK")
